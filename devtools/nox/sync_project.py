    args = parser.parse_args()
    destination = Path(__file__).resolve().parent / "project"
    pairs = [(args.source / "AGENTS.md", destination / "AGENTS.md")]
    pairs += [(args.source / "conversion" / name, destination / name) for name in NAMES]
    # Read every input before writing anything, so a missing source cannot cause
    # partial replacement of the repository recovery copies.
    contents = [(source, target, source.read_bytes()) for source, target in pairs]
    for source, target, data in contents:
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        if not target.is_file() or target.read_bytes() != data:
            raise SystemExit(f"Recovery copy differs: {target}")
        print(f"MATCH {target.name} {hashlib.sha256(data).hexdigest()}")



